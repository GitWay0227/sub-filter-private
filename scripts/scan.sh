#!/usr/bin/env bash
# L1 zombie scan: merge all sources via subconverter -> dedup -> mihomo delay test -> candidates.yaml
# Runs on a GitHub Actions runner. Requires: subconverter/, mihomo, yq, jq
set -euo pipefail
cd "$(dirname "$0")/.."
APIS="http://127.0.0.1:19090"
# Random secret: mihomo listens on loopback only on an ephemeral CI runner;
# randomizing just removes the hardcoded-weak-secret pattern.
SECRET="$(head -c 12 /dev/urandom | base64 | tr -d '=+/')"
export SECRET
NSRC=$(grep -cvE '^#|^$' sources.txt)

# 1. Merge all sources via subconverter (ships its own pref.toml; start from its dir)
(cd subconverter && ./subconverter >/dev/null 2>&1) &
SC_PID=$!
cleanup() { kill "$SC_PID" "${M_PID:-}" 2>/dev/null || true; }
trap cleanup EXIT
for _ in $(seq 1 30); do curl -s -m 2 http://127.0.0.1:25500/version >/dev/null 2>&1 && break; sleep 1; done

URLS=$(grep -vE '^#|^$' sources.txt | paste -sd'|' -)
ENC=$(jq -rn --arg u "$URLS" '$u|@uri')
# subconverter emits broken yaml for some node names/passwords (unescaped quotes,
# bad UTF-8, !<str> tags). iconv strips bad bytes; the per-line pass below drops
# unparseable lines and re-serializes good ones to fix escaping.
curl -s -m 300 "http://127.0.0.1:25500/sub?target=clash&url=$ENC" | iconv -f UTF-8 -t UTF-8 -c > merged.yaml
python3 - <<'PYEOF' > merged-ok.yaml
import yaml
yaml.SafeLoader.add_constructor('str', lambda l, n: l.construct_scalar(n))
out = []
with open('merged.yaml', encoding='utf-8') as f:
    for line in f:
        s = line.rstrip('\n')
        t = s.strip()
        if t.startswith('- {') and t.endswith('}'):
            try:
                node = yaml.safe_load(t[2:])
                if isinstance(node, dict) and node.get('name') and node.get('server') and node.get('port'):
                    out.append('  - ' + yaml.safe_dump(node, default_flow_style=True, allow_unicode=True, width=10000, sort_keys=False).strip())
                    continue
            except Exception:
                pass
            continue
        out.append(s)
print('\n'.join(out))
PYEOF
NMERGE=$(yq '.proxies | length' merged-ok.yaml)
echo "merged: $NMERGE nodes ($NSRC sources)"

# 2. Dedup: first by server:port:secret composite key, then by name.
# Credential fields are tostring-wrapped: some sources ship numeric passwords.
yq '.proxies' merged-ok.yaml -o=json | jq '
    [ .[] | select(.server and .port) ]
  | group_by((((.server//"")|tostring)+":"+(.port|tostring)+":"+((.uuid//.password//.psk//"")|tostring))
    + (((.password//"")|tostring)+((.uuid//"")|tostring)))
  | map(.[0])
  | group_by(.name) | map(.[0])' > dedup.json
TOTAL=$(jq length dedup.json)
echo "deduped: $TOTAL"

# 3. mihomo scan config. A single bad node (bad cipher/field) makes mihomo reject
# the whole config, so -t loop: validate, drop the rejected index, repeat.
mkdir -p .scan
cp dedup.json work.json
for _ in $(seq 1 50); do
  jq '{proxies: .}' work.json | SECRET="$SECRET" yq -P --input-format json '
      .mixed-port = 17890
    | .external-controller = "127.0.0.1:19090"
    | .secret = strenv(SECRET)
    | .log-level = "error"
    | .keep-alive-interval = 30
    | .["find-process-mode"] = "off"' - > scan-config.yaml
  OUT=$(./mihomo -t -f scan-config.yaml -d .scan 2>&1) && break
  N=$(printf '%s' "$OUT" | grep -oP 'proxy \K[0-9]+' | head -1)
  if [ -z "$N" ]; then
    echo "mihomo config error (not node-level):"; printf '%s\n' "$OUT" | grep -v '^time=' | tail -3; exit 1
  fi
  echo "dropping rejected node #$N"
  jq --argjson n "$N" 'del(.[$n])' work.json > w.json && mv w.json work.json
done
./mihomo -d .scan -f scan-config.yaml > mihomo.log 2>&1 &
M_PID=$!
for _ in $(seq 1 30); do curl -s -m 2 -H "Authorization: Bearer $SECRET" "$APIS/version" >/dev/null 2>&1 && break; sleep 1; done
curl -s -m 2 -H "Authorization: Bearer $SECRET" "$APIS/version" >/dev/null || { echo "mihomo failed to start:"; tail -5 mihomo.log; exit 1; }

# 4. Batch delay test (40 workers, 4s timeout per node)
rm -f pass.txt
jq -j '.[].name | tostring + "\u0000"' work.json \
  | xargs -0 -P 40 -n1 scripts/test-one.sh > pass.txt
PASSN=$(tr -cd '\0' < pass.txt | wc -c)
echo "alive: $PASSN"

# 5. Emit candidates.yaml (too few survivors = likely source/network trouble; keep old artifact)
if [ "$PASSN" -lt 20 ]; then
  echo "alive $PASSN < 20, likely source or network trouble; not updating artifact"; exit 1
fi
jq -R -s 'split("\u0000") | map(select(length>0))' pass.txt > pass.json
jq --slurpfile p pass.json \
  '[.[] | select((.name|tostring) as $n | ($p[0] | index($n)) != null)]' work.json > candidates.json
{
  echo "# L1 zombie-scan artifact - generated by GitHub Actions, do not edit"
  echo "# $(date -u '+%F %T') UTC | merged $NMERGE | deduped $TOTAL | alive $PASSN | sources $NSRC"
  jq '{proxies: .}' candidates.json | yq -P --input-format json '.' -
} > candidates.yaml
echo "candidates.yaml: $(grep -cE '^ *- name:' candidates.yaml) nodes"

# 5.5 Emit clash.yaml: import-ready config for human subscribers
# (alive nodes + select/url-test groups + a MATCH rule). pool.yaml/candidates.yaml
# stay proxies-only machine artifacts for L2.
{
  echo "# clash subscription - generated by GitHub Actions, do not edit"
  echo "# $(date -u '+%F %T') UTC | alive $PASSN | sources $NSRC"
  jq '{proxies: .,
       "proxy-groups": [
         {"name": "Pool", "type": "select", "proxies": (["Auto"] + ([.[].name | tostring]))},
         {"name": "Auto", "type": "url-test", "url": "http://www.gstatic.com/generate_204", "interval": 300, "proxies": ([.[].name | tostring])}
       ],
       "rules": ["MATCH,Pool"]}' candidates.json | yq -P --input-format json '.' -
} > clash.yaml
echo "clash.yaml: $(grep -cE '^ *- name:' clash.yaml) nodes"

# 6. Emit pool.yaml: the full validated deduped set (pre-liveness-test).
# L2 scans this whole pool from a China IP so routing-optimized nodes that
# fail the US vantage are not lost.
{
  echo "# L1 deduped pool - generated by GitHub Actions, do not edit"
  echo "# $(date -u '+%F %T') UTC | deduped $TOTAL | sources $NSRC"
  jq '{proxies: .}' work.json | yq -P --input-format json '.' -
} > pool.yaml
echo "pool.yaml: $(grep -cE '^ *- name:' pool.yaml) nodes"
