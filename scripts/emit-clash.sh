#!/usr/bin/env bash
# Emit clash.yaml: import-ready config for human subscribers.
# Reads candidates.json (bare array of alive nodes) and geo.yaml when present
# (with measured exit-country groups); falls back to plain Pool/Auto groups
# when geo.yaml is missing/stale. Called by scan.sh (5.5) and geo-scan.sh.
set -euo pipefail
# Inputs (candidates.json/geo.yaml/sources.txt) live in the caller's working
# directory: repo root when scan.sh/geo-scan.sh call it, standalone otherwise.
# Resolve script dir for nothing but robustness; work where the caller is.
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
echo "emit-clash: workdir $(pwd), script $SCRIPT_DIR" >&2

PASSN=$(jq length candidates.json)
NSRC=$(grep -cvE '^#|^$' sources.txt)

GEO_GROUPS="[]"
if [ -s geo.yaml ] && ! grep -q '^# status:' geo.yaml; then
  GEO_GROUPS=$(python3 - <<'PYEOF'
import yaml, json
try:
    g = yaml.safe_load(open('geo.yaml', encoding='utf-8')).get('groups', {})
except Exception:
    g = {}
print(json.dumps([{"name": c, "type": "select", "proxies": ns}
                  for c, ns in g.items() if ns]))
PYEOF
)
  [ -n "$GEO_GROUPS" ] || GEO_GROUPS="[]"
  echo "clash.yaml: geo groups: $(echo "$GEO_GROUPS" | jq length)"
fi
{
  echo "# clash subscription - generated by GitHub Actions, do not edit"
  echo "# $(date -u '+%F %T') UTC | alive $PASSN | sources $NSRC"
  # Assemble via jq slurpfile (candidates.json can exceed ARG_MAX at ~800 nodes,
  # so no --argjson); groups via a small bridge json.
  jq -n --argjson names "$(jq '[.[].name | tostring]' candidates.json)" \
        --argjson geo "$GEO_GROUPS" \
        --slurpfile proxies candidates.json \
        '{proxies: $proxies[0],
          "proxy-groups": ($geo + [
            {"name": "Pool", "type": "select", "proxies": (["Auto"] + ($geo | map(.name)) + $names)},
            {"name": "Auto", "type": "url-test", "url": "http://www.gstatic.com/generate_204", "interval": 300, "proxies": $names}
          ]),
          "rules": ["MATCH,Pool"]}' | yq -P --input-format json '.' -
} > clash.yaml
echo "clash.yaml: $(grep -cE '^ *- name:' clash.yaml) nodes"
