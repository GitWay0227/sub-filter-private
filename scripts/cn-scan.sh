#!/usr/bin/env bash
# CN-vantage reachability leg: verify China-exit viewpoint nodes (candidates
# from the pre-liveness-test full pool; US-vantage delay testing kills most
# CN-named nodes, so they never reach the alive pool), then test every alive
# node through them via dialer-proxy chains
# (GHA -> viewpoint -> target -> ip echo), grouping by measured exit GeoIP.
# Emits cn-reachable.yaml. Never fails the workflow: on any error it preserves
# the previous artifact (or emits a placeholder) and exits 0.
# Runs after scan.sh on the same runner. Requires: mihomo, jq, curl, python3.
set -uo pipefail
cd "$(dirname "$0")/.."

DIR=.cn-scan
CTRL="127.0.0.1:29090"
SECRET="$(head -c 12 /dev/urandom | base64 | tr -d '=+/')"
export SECRET
CN_RE='中国|CN|China|Beijing|Shanghai|Guangzhou|Shenzhen|Hangzhou|Chengdu|Nanjing|Chongqing|Wuhan|Tianjin|Qingdao|北京|上海|广州|深圳|杭州|成都|南京|重庆|武汉|天津|青岛'
gen() { python3 scripts/cn-gen.py "$@"; }

# 1100+ listeners exceed the default 1024 soft nofile limit on GitHub runners.
ulimit -n 65536 2>/dev/null || true

printf '# cn-reachable - generated by GitHub Actions, do not edit\n# status: pending\n' > cn-reachable.yaml

mkdir -p "$DIR"
M_PID=""
trap '[ -n "$M_PID" ] && kill "$M_PID" 2>/dev/null; true' EXIT

preserve() {
  if git fetch -q origin artifacts 2>/dev/null \
     && git show origin/artifacts:cn-reachable.yaml > "$DIR/old.yaml" 2>/dev/null \
     && [ -s "$DIR/old.yaml" ] \
     && ! grep -q '^# status: pending' "$DIR/old.yaml"; then
    { echo "# preserved on $(date -u '+%F %T') UTC - original content follows"
      cat "$DIR/old.yaml"; } > cn-reachable.yaml
    echo "cn-scan: kept previous cn-reachable.yaml"
  else
    printf '# cn-reachable - generated by GitHub Actions, do not edit\n# status: unavailable (%s UTC)\n' \
      "$(date -u '+%F %T')" > cn-reachable.yaml
    echo "cn-scan: no usable previous artifact, wrote unavailable placeholder"
  fi
}

start_mihomo() {  # $1 = config path
  ./mihomo -t -f "$1" -d "$DIR" >/dev/null 2>&1 || { echo "cn-scan: config test failed: $1"; return 1; }
  ./mihomo -d "$DIR" -f "$1" > "$DIR/mihomo.log" 2>&1 &
  M_PID=$!
  for _ in $(seq 1 30); do
    curl -s -m 2 -H "Authorization: Bearer $SECRET" "http://$CTRL/version" >/dev/null 2>&1 && return 0
    sleep 1
  done
  echo "cn-scan: mihomo failed to start"; return 1
}
stop_mihomo() {
  [ -n "$M_PID" ] && kill "$M_PID" 2>/dev/null
  [ -n "$M_PID" ] && wait "$M_PID" 2>/dev/null
  M_PID=""
}

# probe.sh: one job line "port<TAB>probe_name<TAB>report_name<TAB>vp" as $1;
# env: PROBE_TMO, IPAPI, IPSB. Prints "report_name<TAB>CC<TAB>ip<TAB>vp" on success.
cat > "$DIR/probe.sh" <<'PEOF'
#!/usr/bin/env bash
IFS=$'\t' read -r port _pn name vp <<< "$1"
res=$(curl -x "http://127.0.0.1:$port" -s -m "$PROBE_TMO" -w '\n%{http_code}' "$IPAPI" 2>/dev/null) || exit 0
code=${res##*$'\n'}
body=${res%$'\n'*}
cc=""; ip=""
if [ "$code" = "200" ]; then
  cc=$(jq -r 'if .status=="success" then (.countryCode//"") else "" end' <<<"$body" 2>/dev/null)
  ip=$(jq -r '.query // ""' <<<"$body" 2>/dev/null)
fi
# Empty result covers: non-200 (incl. 429 rate limit), parse failure, bad body.
# Retry via the fallback echo service before giving up on this node.
if [ -z "$cc" ] || [ -z "$ip" ]; then
  res=$(curl -x "http://127.0.0.1:$port" -s -m "$PROBE_TMO" -w '\n%{http_code}' "$IPSB" 2>/dev/null) || exit 0
  code=${res##*$'\n'}
  body=${res%$'\n'*}
  [ "$code" = "200" ] || exit 0
  cc=$(jq -r '.country_code // ""' <<<"$body" 2>/dev/null)
  ip=$(jq -r '.ip // ""' <<<"$body" 2>/dev/null)
fi
[ -n "$cc" ] && [ -n "$ip" ] && printf '%s\t%s\t%s\t%s\n' "$name" "$(printf '%s' "$cc" | tr a-z A-Z)" "$ip" "$vp"
PEOF

probe_all() {  # $1 = jobs tsv, $2 = timeout secs, $3 = out tsv
  : > "$3"
  PROBE_TMO="$2" IPAPI="http://ip-api.com/json/?fields=status,query,countryCode" \
    IPSB="https://api.ip.sb/geoip" \
    xargs -d '\n' -P 40 -n1 bash "$DIR/probe.sh" < "$1" >> "$3" || true
}

# Names in pool/candidates that produced no probe result.
missing() {  # $1 = candidate names json, $2 = results tsv, $3 = out json
  cut -f1 "$2" 2>/dev/null | jq -R -s 'split("\n")|map(select(length>0))' > "$DIR/_have.json"
  jq --slurpfile r "$DIR/_have.json" \
    '[.[] | select((. as $n | ($r[0] | index($n))) == null)]' "$1" > "$3"
}

[ -s candidates.json ] && [ -s work.json ] || { echo "cn-scan: no candidates.json/work.json"; preserve; exit 0; }

# ---- Phase A: verify China-exit viewpoints ----
# Candidates come from work.json (pre-liveness-test full pool), NOT the alive
# pool: US-vantage delay testing kills most CN-named nodes, so the alive pool
# usually contains none. Phase A itself is their liveness+exit verification.
gen cands work.json "$DIR/cands.json" 100 "$CN_RE" || { preserve; exit 0; }
NC=$(jq length "$DIR/cands.json")
echo "cn-scan: phase A: $NC CN-name candidates"
[ "$NC" -gt 0 ] || { preserve; exit 0; }

gen config direct "$DIR/cfg-a.yaml" "$DIR/jobs-a.tsv" candidates.json "$DIR/cands.json" work.json || { preserve; exit 0; }
start_mihomo "$DIR/cfg-a.yaml" || { preserve; exit 0; }
probe_all "$DIR/jobs-a.tsv" 12 "$DIR/res-a.tsv"
stop_mihomo
echo "cn-scan: phase A direct: $(wc -l < "$DIR/res-a.tsv") probed, $(awk -F'\t' '$2=="CN"' "$DIR/res-a.tsv" | wc -l) verified CN exit"

# Candidates with no result at all may have domestic-only entries: retry
# through pool relay nodes ("reachable via a relay counts as reachable").
gen fers candidates.json "$DIR/fers.json" "$DIR/cands.json"
missing "$DIR/cands.json" "$DIR/res-a.tsv" "$DIR/failed-cands.json"
NF=$(jq length "$DIR/failed-cands.json")
if [ "$NF" -gt 0 ]; then
  echo "cn-scan: phase A: retrying $NF candidates via relay"
  gen config relay "$DIR/cfg-ar.yaml" "$DIR/jobs-ar.tsv" candidates.json "$DIR/failed-cands.json" "$DIR/fers.json" work.json || { preserve; exit 0; }
  start_mihomo "$DIR/cfg-ar.yaml" || { preserve; exit 0; }
  probe_all "$DIR/jobs-ar.tsv" 12 "$DIR/res-ar.tsv"
  stop_mihomo
  echo "cn-scan: phase A relay: $(wc -l < "$DIR/res-ar.tsv") probed, $(awk -F'\t' '$2=="CN"' "$DIR/res-ar.tsv" | wc -l) verified CN exit"
else
  : > "$DIR/res-ar.tsv"
fi

gen vpset "$DIR/vps.json" "$DIR/cnset.json" "$DIR/res-a.tsv" "$DIR/res-ar.tsv" 2 || { preserve; exit 0; }
KV=$(jq length "$DIR/vps.json")
echo "cn-scan: $KV verified viewpoints, $(jq length "$DIR/cnset.json") CN nodes"
[ "$KV" -gt 0 ] || { preserve; exit 0; }

# ---- Phase B: test every alive node through the viewpoints ----
jq '[.[] | (.name|tostring)]' candidates.json > "$DIR/all-names.json"
gen config chain "$DIR/cfg-b1.yaml" "$DIR/jobs-b1.tsv" candidates.json work.json "$DIR/vps.json" "$DIR/all-names.json" 0 || { preserve; exit 0; }
start_mihomo "$DIR/cfg-b1.yaml" || { preserve; exit 0; }
probe_all "$DIR/jobs-b1.tsv" 15 "$DIR/res-b1.tsv"
stop_mihomo
echo "cn-scan: phase B round 1: $(wc -l < "$DIR/res-b1.tsv") reachable"

# Retry failures once on the next viewpoint (only meaningful with 2+ viewpoints).
# Guarded by elapsed time: with an all-timeout round 1 the retry could push the
# whole leg past the workflow's 720s timeout and lose everything.
if [ "$KV" -gt 1 ] && [ "$SECONDS" -lt 420 ]; then
  missing "$DIR/all-names.json" "$DIR/res-b1.tsv" "$DIR/failed-b.json"
  NB=$(jq length "$DIR/failed-b.json")
  if [ "$NB" -gt 0 ]; then
    echo "cn-scan: phase B: retrying $NB failed nodes on another viewpoint (${SECONDS}s elapsed)"
    gen config chain "$DIR/cfg-b2.yaml" "$DIR/jobs-b2.tsv" candidates.json work.json "$DIR/vps.json" "$DIR/failed-b.json" 1 || { preserve; exit 0; }
    start_mihomo "$DIR/cfg-b2.yaml" || { preserve; exit 0; }
    probe_all "$DIR/jobs-b2.tsv" 15 "$DIR/res-b2.tsv"
    stop_mihomo
    echo "cn-scan: phase B round 2: $(wc -l < "$DIR/res-b2.tsv") more reachable"
  else
    : > "$DIR/res-b2.tsv"
  fi
else
  if [ "$KV" -gt 1 ]; then echo "cn-scan: phase B: skipping retry round (${SECONDS}s elapsed)"; fi
  : > "$DIR/res-b2.tsv"
fi

# ---- Assemble artifact ----
gen emit cn-reachable.yaml candidates.json work.json "$DIR/vps.json" "$DIR/cnset.json" "$DIR/res-b1.tsv" "$DIR/res-b2.tsv" || { preserve; exit 0; }
NR=$(yq '.stats.reachable // 0' cn-reachable.yaml 2>/dev/null || echo 0)
if [ "$NR" -lt 1 ] 2>/dev/null; then
  echo "cn-scan: reachable=0, likely network trouble"
  preserve
  exit 0
fi
echo "cn-scan: cn-reachable.yaml written with $NR reachable nodes"
exit 0
