#!/usr/bin/env bash
# Geo-exit leg: measure each alive node's real exit IP and country via its own
# mihomo listener, then emit geo.yaml (groups keyed by measured exit country).
# Failure-isolated like cn-scan.sh: on any error it preserves the previous
# geo.yaml (or emits a placeholder) and exits 0, never blocking L1 artifacts.
# Runs after scan.sh on the same runner. Requires: mihomo, jq, curl, python3.
set -uo pipefail
cd "$(dirname "$0")/.."

DIR=.geo-scan
CTRL="127.0.0.1:29190"
SECRET="$(head -c 12 /dev/urandom | base64 | tr -d '=+/')"
export SECRET
# One listener per alive node (BASE_PORT + i); ip-api.com is 45 req/min per IP
# but each request exits from a different node IP, so per-IP limits don't apply.
PROBE_TMO="${GEO_PROBE_TMO:-10}"
MAX_AGE_MIN="${GEO_MAX_AGE_MIN:-5}"

gen() { python3 scripts/cn-gen.py "$@"; }

ulimit -n 65536 2>/dev/null || true

fresh_placeholder() {
  printf '# geo-exit - generated by GitHub Actions, do not edit\n# status: unavailable (%s UTC)\n' \
    "$(date -u '+%F %T')" > geo.yaml
}
fresh_placeholder
mkdir -p "$DIR"
M_PID=""
trap '[ -n "$M_PID" ] && kill "$M_PID" 2>/dev/null; true' EXIT

preserve() {
  if git fetch -q origin artifacts 2>/dev/null \
     && git show origin/artifacts:geo.yaml > "$DIR/old.yaml" 2>/dev/null \
     && [ -s "$DIR/old.yaml" ] \
     && ! grep -q '^# status:' "$DIR/old.yaml"; then
    { echo "# preserved on $(date -u '+%F %T') UTC - original content follows"
      cat "$DIR/old.yaml"; } > geo.yaml
    echo "geo-scan: kept previous geo.yaml"
  else
    fresh_placeholder
    echo "geo-scan: no usable previous artifact, wrote unavailable placeholder"
  fi
}

[ -s candidates.json ] || { echo "geo-scan: no candidates.json"; preserve; exit 0; }
NALIVE=$(jq length candidates.json)
[ "$NALIVE" -gt 0 ] || { echo "geo-scan: empty alive pool"; preserve; exit 0; }

gen config geo "$DIR/cfg-geo.yaml" "$DIR/jobs-geo.tsv" candidates.json || { preserve; exit 0; }
./mihomo -t -f "$DIR/cfg-geo.yaml" -d "$DIR" >/dev/null 2>&1 || { echo "geo-scan: config test failed"; preserve; exit 0; }
./mihomo -d "$DIR" -f "$DIR/cfg-geo.yaml" > "$DIR/mihomo.log" 2>&1 &
M_PID=$!
for _ in $(seq 1 30); do
  curl -s -m 2 -H "Authorization: Bearer $SECRET" "http://$CTRL/version" >/dev/null 2>&1 && break
  sleep 1
done
curl -s -m 2 -H "Authorization: Bearer $SECRET" "$CTRL/version" >/dev/null || {
  echo "geo-scan: mihomo failed to start"; tail -5 "$DIR/mihomo.log"; preserve; exit 0; }

# probe.sh: one job line "port<TAB>probe_name<TAB>report_name" as $1.
# Prints "report_name<TAB>CC<TAB>ip" on success; empty country = unresolved.
cat > "$DIR/probe.sh" <<'PEOF'
#!/usr/bin/env bash
IFS=$'\t' read -r port _pn name <<< "$1"
res=$(curl -x "http://127.0.0.1:$port" -s -m "$PROBE_TMO" -w '\n%{http_code}' \
  "http://ip-api.com/json/?fields=status,query,countryCode" 2>/dev/null) || exit 0
code=${res##*$'\n'}
body=${res%$'\n'*}
cc=""; ip=""
if [ "$code" = "200" ]; then
  cc=$(jq -r 'if .status=="success" then (.countryCode//"") else "" end' <<<"$body" 2>/dev/null)
  ip=$(jq -r '.query // ""' <<<"$body" 2>/dev/null)
fi
if [ -z "$cc" ] || [ -z "$ip" ]; then
  res=$(curl -x "http://127.0.0.1:$port" -s -m "$PROBE_TMO" -w '\n%{http_code}' \
    "https://api.ip.sb/geoip" 2>/dev/null) || exit 0
  code=${res##*$'\n'}
  body=${res%$'\n'*}
  [ "$code" = "200" ] || exit 0
  cc=$(jq -r '.country_code // ""' <<<"$body" 2>/dev/null)
  ip=$(jq -r '.ip // ""' <<<"$body" 2>/dev/null)
fi
[ -n "$ip" ] && printf '%s\t%s\t%s\n' "$name" "$(printf '%s' "$cc" | tr a-z A-Z)" "$ip"
PEOF

: > "$DIR/res-geo.tsv"
SECONDS=0
xargs -d '\n' -P 40 -n1 bash "$DIR/probe.sh" < "$DIR/jobs-geo.tsv" >> "$DIR/res-geo.tsv" || true
GOT=$(wc -l < "$DIR/res-geo.tsv")
echo "geo-scan: $GOT/$NALIVE probed in ${SECONDS}s"

# Too few probes = likely runner network trouble; keep the previous artifact.
if [ "$GOT" -lt $((NALIVE / 2)) ]; then
  echo "geo-scan: probe success rate too low, preserving previous geo.yaml"
  preserve
  exit 0
fi

gen geoemit geo.yaml candidates.json "$DIR/res-geo.tsv" "$PROBE_TMO" || { preserve; exit 0; }
NG=$(python3 -c "import yaml,sys; print(len(yaml.safe_load(open('geo.yaml')).get('groups',{})))" 2>/dev/null || echo 0)
[ "$NG" -gt 0 ] || { echo "geo-scan: no country groups, preserving previous"; preserve; exit 0; }
echo "geo-scan: geo.yaml written with $NG country groups"
exit 0
